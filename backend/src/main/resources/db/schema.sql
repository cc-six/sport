-- 体育馆管理系统数据库初始化脚本
-- MySQL 8.0+
-- 支持重复执行：先删后建，幂等初始化

-- ============================================================
-- 清理已有表（按外键依赖逆序删除）
-- ============================================================
DROP TABLE IF EXISTS rental;
DROP TABLE IF EXISTS `order`;
DROP TABLE IF EXISTS equipment;
DROP TABLE IF EXISTS venue;
DROP TABLE IF EXISTS user;
DROP TABLE IF EXISTS role;

CREATE DATABASE IF NOT EXISTS sport_hall DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE sport_hall;

-- 角色表
CREATE TABLE role (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(50) NOT NULL UNIQUE COMMENT '角色名: admin / user'
) COMMENT '角色表';

-- 用户表
CREATE TABLE user (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    username VARCHAR(50) NOT NULL UNIQUE COMMENT '用户名',
    password VARCHAR(100) NOT NULL COMMENT '密码',
    phone VARCHAR(20) COMMENT '手机号',
    role_id BIGINT NOT NULL DEFAULT 2 COMMENT '角色外键',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (role_id) REFERENCES role(id)
) COMMENT '用户表';

-- 场地表
CREATE TABLE venue (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL COMMENT '场地名称',
    type VARCHAR(50) NOT NULL COMMENT '类型: 羽毛球/篮球/乒乓球',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '状态: 0-下架 1-上架',
    open_time TIME NOT NULL COMMENT '开放开始时间',
    close_time TIME NOT NULL COMMENT '开放结束时间',
    price_per_hour DECIMAL(10,2) NOT NULL COMMENT '每小时价格',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) COMMENT '场地表';

-- 订单表
CREATE TABLE `order` (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    order_no VARCHAR(32) NOT NULL UNIQUE COMMENT '订单编号',
    user_id BIGINT NOT NULL COMMENT '用户外键',
    venue_id BIGINT NOT NULL COMMENT '场地外键',
    book_date DATE NOT NULL COMMENT '预约日期',
    start_time TIME NOT NULL COMMENT '开始时段',
    end_time TIME NOT NULL COMMENT '结束时段',
    total_amount DECIMAL(10,2) NOT NULL COMMENT '总金额',
    status TINYINT NOT NULL DEFAULT 0 COMMENT '0-待支付 1-已支付 2-已取消',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES user(id),
    FOREIGN KEY (venue_id) REFERENCES venue(id)
) COMMENT '订单表';

-- 器材表
CREATE TABLE equipment (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL COMMENT '器材名称',
    total_qty INT NOT NULL DEFAULT 0 COMMENT '总数量',
    available_qty INT NOT NULL DEFAULT 0 COMMENT '可借数量',
    price_per_hour DECIMAL(10,2) NOT NULL COMMENT '租借单价',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) COMMENT '器材表';

-- 租借记录表
CREATE TABLE rental (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL COMMENT '用户外键',
    equipment_id BIGINT NOT NULL COMMENT '器材外键',
    quantity INT NOT NULL COMMENT '租借数量',
    status TINYINT NOT NULL DEFAULT 0 COMMENT '0-租借中 1-已归还',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    return_time DATETIME COMMENT '归还时间',
    FOREIGN KEY (user_id) REFERENCES user(id),
    FOREIGN KEY (equipment_id) REFERENCES equipment(id)
) COMMENT '租借记录表';

